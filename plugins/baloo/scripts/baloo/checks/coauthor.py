"""The Check no-ai-coauthor."""

from __future__ import annotations

import re
from typing import List

# An AI named in a co-author trailer or a credit line: Claude with a model, Code or its email, or a
# coding agent by a name or an email no person has.
_AI = re.compile(
    r"\bclaude (code|opus|sonnet|haiku|fable|\d)|@anthropic\.com|"
    r"\bcopilot\b|\bcursor agent\b|@cursor\.(com|sh)|\bchatgpt\b|\bcodex\b|@openai\.com|"
    r"\bgemini\b|devin-ai-integration|\baider\b|@ampcode\.com",
    re.I | re.A,
)
# A co-author trailer, with the co-author's name.
_COAUTHOR = re.compile(r"^\s*co-authored-by:\s*([^<]*?)\s*(<|$)", re.I | re.A)
# A line crediting a tool with the commit: `Generated with …`, `🤖 Generated by …`.
_CREDIT = re.compile(r"^\s*(🤖\s*)?generated (with|by)\s", re.I | re.A)
_ROBOT = re.compile(r"^\s*🤖", re.A)
_CLAUDE = re.compile(r"\bclaude\b", re.I | re.A)
# Where `git commit -v` puts the diff below the message.
SCISSORS = re.compile(r"^# -+ >8 -+$", re.M)


def no_ai_coauthor(message: str) -> List[str]:
    """The Check baloo:no-ai-coauthor (commit-msg): the lines of the commit message that make an AI
    its co-author or credit one with it. A person's co-author trailer passes, even one named Claude
    with a surname; a co-author named only Claude is the AI. In a credit line a bare Claude is the
    AI too, since a person generates no commit, and the robot always marks one."""
    found = []
    for line in SCISSORS.split(message, 1)[0].split("\n"):
        m = _COAUTHOR.search(line)
        if m:
            if _AI.search(line) or m[1].lower() == "claude":
                found.append(line)
        elif _CREDIT.search(line) and (
            _AI.search(line) or _CLAUDE.search(line) or _ROBOT.search(line)
        ):
            found.append(line)
    return found
